   public static void revealMatrix(ServerLevel l, CampaignSavedData d) {
      BlockPos m = d.matrixPos();
      if (!m.equals(BlockPos.ZERO)) {
         for (int dx = -1; dx <= 1; dx++) {
            for (int dy = 0; dy <= 2; dy++) {
               for (int dz = -1; dz <= 1; dz++) {
                  BlockPos p = m.offset(dx, dy, dz);
                  if (!p.equals(m)) {
                     l.setBlock(p, Blocks.AIR.defaultBlockState(), 3);
                  }
               }
            }
         }

         l.setBlock(m, ((Block)ReivaxMCProgress.ORIGIN_MATRIX.get()).defaultBlockState(), 3);
         l.sendParticles(ParticleTypes.ENCHANT, (double)m.getX() + 0.5, (double)m.getY() + 0.8, (double)m.getZ() + 0.5, 45, 0.6, 0.7, 0.6, 0.08);
         l.playSound(null, m, SoundEvents.RESPAWN_ANCHOR_CHARGE, SoundSource.BLOCKS, 0.8F, 0.7F);
      }
   }

   private static void buildStela(ServerLevel l, BlockPos c, CampaignSavedData d) {
      RandomSource r = l.getRandom();
      int y = c.getY();
      preparePad(l, c, 7, y);

      for (int dx = -7; dx <= 7; dx++) {
         for (int dz = -7; dz <= 7; dz++) {
            double q = Math.sqrt((double)(dx * dx + dz * dz));
            if (q < 6.8 && (double)r.nextFloat() > 0.18) {
               BlockPos p = c.offset(dx, -1, dz);
               l.setBlock(p, ((double)r.nextFloat() < 0.35 ? Blocks.MOSSY_STONE_BRICKS : Blocks.TUFF_BRICKS).defaultBlockState(), 3);
               support(l, p, 4);
            }
         }
      }

      for (int h = 0; h < 6; h++) {
         l.setBlock(c.offset(0, h, 3), (h == 3 ? Blocks.GILDED_BLACKSTONE : Blocks.POLISHED_TUFF).defaultBlockState(), 3);
      }

      l.setBlock(c.offset(0, 2, 3), Blocks.CHISELED_DEEPSLATE.defaultBlockState(), 3);

      for (int[] a : new int[][]{{-5, -4, 4}, {5, -4, 5}, {-5, 4, 3}, {5, 4, 4}}) {
         for (int h = 0; h < a[2]; h++) {
            if (h != a[2] - 1 || !r.nextBoolean()) {
               l.setBlock(c.offset(a[0], h, a[1]), Blocks.TUFF_BRICKS.defaultBlockState(), 3);
            }
         }
      }

      for (int step = 0; step < 4; step++) {
         for (int x = -1; x <= 1; x++) {
            BlockPos p = c.offset(x, -step, -4 - step);
            l.setBlock(p, Blocks.POLISHED_TUFF.defaultBlockState(), 3);

            for (int hx = 1; hx <= 3; hx++) {
               l.setBlock(p.above(hx), Blocks.AIR.defaultBlockState(), 3);
            }
         }
      }

      BlockPos room = c.offset(0, -3, -8);

      for (int dx = -4; dx <= 4; dx++) {
         for (int dzx = -4; dzx <= 4; dzx++) {
            for (int dy = 0; dy <= 4; dy++) {
               boolean shell = dx == -4 || dx == 4 || dzx == -4 || dzx == 4 || dy == 0 || dy == 4;
               BlockPos p = room.offset(dx, dy, dzx);
               if (shell) {
                  l.setBlock(p, ((double)r.nextFloat() < 0.18 ? Blocks.MOSSY_STONE_BRICKS : Blocks.DEEPSLATE_BRICKS).defaultBlockState(), 3);
               } else {
                  l.setBlock(p, Blocks.AIR.defaultBlockState(), 3);
               }
            }
         }
      }

      for (int dyx = 1; dyx <= 3; dyx++) {
         for (int x = -1; x <= 1; x++) {
            l.setBlock(room.offset(x, dyx, 4), Blocks.AIR.defaultBlockState(), 3);
         }
      }

      BlockPos altar = room.offset(0, 1, -1);
      l.setBlock(altar, ((Block)ReivaxMCProgress.FRAGMENT_ALTAR.get()).defaultBlockState(), 3);
      d.setAltar(altar);
      BlockPos matrix = room.offset(0, 1, -3);
      d.setMatrixPos(matrix);
      l.setBlock(room.offset(-3, 1, -3), Blocks.SOUL_LANTERN.defaultBlockState(), 3);
      l.setBlock(room.offset(3, 1, -3), Blocks.SOUL_LANTERN.defaultBlockState(), 3);
   }

   private static void preparePad(ServerLevel l, BlockPos c, int radius, int y) {
      for (int dx = -radius; dx <= radius; dx++) {
         for (int dz = -radius; dz <= radius; dz++) {
            int sy = surface(l, c.getX() + dx, c.getZ() + dz);
            if (sy > y + 1) {
               for (int yy = y; yy <= Math.min(sy + 2, y + 7); yy++) {
                  l.setBlock(new BlockPos(c.getX() + dx, yy, c.getZ() + dz), Blocks.AIR.defaultBlockState(), 3);
               }
            }
         }
      }
   }

   private static void support(ServerLevel l, BlockPos p, int depth) {
      for (int k = 1; k <= depth; k++) {
         BlockPos q = p.below(k);
         if (!l.getBlockState(q).isAir()) {
            break;
         }

         l.setBlock(q, Blocks.TUFF.defaultBlockState(), 3);
      }
   }

   private static int surface(ServerLevel l, int x, int z) {
      return l.getHeight(Types.MOTION_BLOCKING_NO_LEAVES, x, z);
   }

   private static BlockPos findValid(ServerLevel l, BlockPos o, int minD, int maxD, int radius, int maxRange, int tries) {
      RandomSource r = l.getRandom();

      for (int n = 0; n < tries; n++) {
         double a = r.nextDouble() * Math.PI * 2.0;
         int dist = minD + r.nextInt(Math.max(1, maxD - minD + 1));
         int x = o.getX() + (int)Math.round(Math.cos(a) * (double)dist);
         int z = o.getZ() + (int)Math.round(Math.sin(a) * (double)dist);
         List<Integer> ys = new ArrayList<>();
         boolean bad = false;

         for (int dx = -radius; dx <= radius; dx += 2) {
            for (int dz = -radius; dz <= radius; dz += 2) {
               if (dx * dx + dz * dz <= radius * radius) {
                  int sy = surface(l, x + dx, z + dz);
                  ys.add(sy);
                  BlockPos ground = new BlockPos(x + dx, sy - 1, z + dz);
                  if (sy < l.getMinBuildHeight() + 12
                     || sy > l.getMaxBuildHeight() - 12
                     || !l.getFluidState(ground).isEmpty()
                     || !l.getFluidState(ground.above()).isEmpty()
                     || !l.getBlockState(ground).isSolid()) {
                     bad = true;
                     break;
                  }

                  for (int k = 1; k <= 3; k++) {
                     if (l.getBlockState(ground.below(k)).isAir()) {
                        bad = true;
                        break;
                     }
                  }

                  if (bad) {
                     break;
                  }
               }
            }
         }

         if (!bad && !ys.isEmpty()) {
            Collections.sort(ys);
            int lo = ys.get(0);
            int hi = ys.get(ys.size() - 1);
            int median = ys.get(ys.size() / 2);
            if (hi - lo <= maxRange) {
               int supported = 0;
               int total = 0;

               for (int dx = -radius; dx <= radius; dx += 2) {
                  for (int dzx = -radius; dzx <= radius; dzx += 2) {
                     if (dx * dx + dzx * dzx <= radius * radius) {
                        total++;
                        int syx = surface(l, x + dx, z + dzx);
                        if (Math.abs(syx - median) <= 3) {
                           supported++;
                        }
                     }
                  }
               }

               if (!((double)supported < (double)total * 0.94)) {
                  return new BlockPos(x, median, z);
               }
            }
         }
      }

      return null;
   }

